"""Generate per-tile brightness corrections so the starfield backgrounds of adjacent systems match.

The tile PNGs come from different artists/batches and their space backdrop varies in brightness.
Metric = 35th percentile of luminance inside the hex (planets/labels are brighter and sit above
that percentile; the backdrop dominates it). Factor = target / metric, clamped to [0.8, 1.6],
where target = GAIN * median metric of all regular hex tiles.

Run: uv run --with pillow --with numpy python scripts/gen_tile_brightness.py
Output: frontend/src/entities/geometry/tileBrightness.generated.ts (keyed by image file name).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
TILES = ROOT / "assets" / "tiles"
OUT = ROOT / "frontend" / "src" / "entities" / "geometry" / "tileBrightness.generated.ts"
CLAMP = (0.8, 1.6)
# Whole board lift on top of equalizing (1.0 = keep the median tile as it is).
GAIN = 1.2
PERCENTILE = 35


def metric(path: Path) -> float | None:
    img = Image.open(path).convert("RGBA")
    if img.size != (345, 299):  # spiral/irregular tiles are not normalized
        return None
    arr = np.asarray(img).astype(float)
    alpha = arr[:, :, 3] > 250
    lum = 0.2126 * arr[:, :, 0] + 0.7152 * arr[:, :, 1] + 0.0722 * arr[:, :, 2]
    # inner region only (skip the frame rim)
    mask = alpha.copy()
    mask[:20, :] = mask[-20:, :] = False
    mask[:, :30] = mask[:, -30:] = False
    if mask.sum() < 5000:
        return None
    return float(np.percentile(lum[mask], PERCENTILE))


def main() -> None:
    metrics = {p.name: m for p in sorted(TILES.glob("*.png")) if (m := metric(p)) is not None}
    target = float(np.median(list(metrics.values()))) * GAIN
    lines = [
        "// GENERATED by scripts/gen_tile_brightness.py - do not edit by hand.",
        "// Brightness multiplier per tile image so neighbouring starfields match.",
        "",
        "export const TILE_BRIGHTNESS: Record<string, number> = {",
    ]
    for name, m in metrics.items():
        f = min(max(target / max(m, 1.0), CLAMP[0]), CLAMP[1])
        if abs(f - 1) >= 0.03:
            lines.append(f'  "{name}": {f:.2f},')
    lines += ["};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    vals = np.array(list(metrics.values()))
    print(f"tiles={len(vals)} target={target:.1f} p5={np.percentile(vals,5):.1f} p95={np.percentile(vals,95):.1f}")


main()
